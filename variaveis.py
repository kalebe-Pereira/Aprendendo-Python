                    # TIPOS DE DADOS

# No Python, temos os seguintes tipos de dados:
        # int -> Tipo inteiro - Usado para número Naturais(1,2,3,4...) .

        # string -> Tipo Caracter - Usado para texto: "Olá".
        
        # float ->  Tipo de ponto flutuante - Usado para número com casas decimal
        
        # bool -> Tipo boleano - Utilizado quando  há uma condição de verdadeiro ou falso
        
# Exemplos

numero = 1
texto = "Olá, Mundo!"
ponto = 3.1415
boleano = True

print(numero)
print(texto)
print(ponto)
print(boleano)

