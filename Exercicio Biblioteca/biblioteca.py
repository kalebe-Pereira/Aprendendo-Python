# Bibliotecas são um conjunto de módulos. O python já possui algumas bibliotecas padrões, como por exemplo o math:

import math

# No math, temos a função de calcular raiz quadrada chamada sqrt:

math.sqrt(81)

# Tem outras funções do math, que são:

math.ceil(7.8) # Arredonda um valor.
math.pi # Valor de pi
math.factorial(4) # Retorna o fatorial do valor.

# Outra biblioteca muito usada é o random:

import random

random.randint(1, 10) # Retorna um valor inteiro aleatório entre os valores passados.
